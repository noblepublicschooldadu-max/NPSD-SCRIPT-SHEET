export const ADMISSION_STATUSES = ["submitted", "under_review", "additional_information_required", "approved", "rejected", "waitlisted"] as const;
export type AdmissionStatus = typeof ADMISSION_STATUSES[number];
export type AdmissionApplicationInput = {
  applicantName: string;
  dateOfBirth: string;
  requestedClass: number;
  guardianName: string;
  guardianPhone: string;
  address: string;
  previousSchool?: string;
  existingGrNumber?: string;
  academicYear?: string;
  consent: boolean;
};
export type AdmissionApplication = AdmissionApplicationInput & {
  id: string;
  reference: string;
  status: AdmissionStatus;
  submittedAt: string;
  updatedAt: string;
  reviewNote?: string;
  reviewedBy?: string;
  reviewedAt?: string;
  linkedStudentId?: string;
  version: number;
};
export type AdmissionFieldErrors = Partial<Record<keyof AdmissionApplicationInput, string>>;

export function validCalendarDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00.000Z`);
  return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

export function normalizePakistanPhone(value: string): string | null {
  const compact = value.trim().replace(/[\s()-]/g, "");
  const normalized = compact.startsWith("+92") ? `0${compact.slice(3)}` : compact.startsWith("0092") ? `0${compact.slice(4)}` : compact;
  return /^03\d{9}$/.test(normalized) ? normalized : null;
}

export function validateAdmissionApplication(input: Partial<AdmissionApplicationInput>, now = new Date()): AdmissionFieldErrors {
  const errors: AdmissionFieldErrors = {};
  if (typeof input.applicantName !== "string" || input.applicantName.trim().length < 2 || input.applicantName.trim().length > 120) errors.applicantName = "Enter the applicant's full name (2–120 characters).";
  if (typeof input.dateOfBirth !== "string" || !validCalendarDate(input.dateOfBirth) || new Date(`${input.dateOfBirth}T00:00:00.000Z`).getTime() > now.getTime()) errors.dateOfBirth = "Enter a valid date of birth that is not in the future.";
  if (!Number.isInteger(input.requestedClass) || Number(input.requestedClass) < 1 || Number(input.requestedClass) > 8) errors.requestedClass = "Select a class from 1 to 8.";
  if (typeof input.guardianName !== "string" || input.guardianName.trim().length < 2 || input.guardianName.trim().length > 120) errors.guardianName = "Enter a parent or guardian name (2–120 characters).";
  if (typeof input.guardianPhone !== "string" || !normalizePakistanPhone(input.guardianPhone)) errors.guardianPhone = "Enter a valid Pakistan mobile number, e.g. 03XXXXXXXXX.";
  if (typeof input.address !== "string" || input.address.trim().length < 5 || input.address.trim().length > 500) errors.address = "Enter a current address (5–500 characters).";
  if (input.previousSchool !== undefined && (typeof input.previousSchool !== "string" || input.previousSchool.trim().length > 160)) errors.previousSchool = "Previous school must be 160 characters or fewer.";
  if (input.existingGrNumber !== undefined && (typeof input.existingGrNumber !== "string" || input.existingGrNumber.trim().length > 40)) errors.existingGrNumber = "Existing GR/Seat Number must be 40 characters or fewer.";
  if (input.academicYear !== undefined && (typeof input.academicYear !== "string" || input.academicYear.trim().length > 40)) errors.academicYear = "Academic year must be 40 characters or fewer.";
  if (input.consent !== true) errors.consent = "Consent is required to submit this application.";
  return errors;
}

export function isAdmissionStatusTransitionAllowed(from: AdmissionStatus, to: AdmissionStatus): boolean {
  const allowed: Record<AdmissionStatus, AdmissionStatus[]> = {
    submitted: ["under_review", "additional_information_required", "approved", "rejected", "waitlisted"],
    under_review: ["additional_information_required", "approved", "rejected", "waitlisted"],
    additional_information_required: ["under_review", "approved", "rejected", "waitlisted"],
    waitlisted: ["under_review", "approved", "rejected"],
    approved: [],
    rejected: [],
  };
  return from !== to && allowed[from].includes(to);
}

/** A retry key is deterministic but must be enforced by the trusted backend, not the browser alone. */
export function admissionOperationKey(applicationId: string, action: string, version: number): string {
  return `${applicationId.trim()}:${action.trim()}:${version}`;
}

/** Public identifiers must be cryptographically unpredictable and generated by the trusted backend. */
export function isSafePublicApplicationReference(value: unknown): value is string {
  return typeof value === "string" && /^NPSD-[A-Z0-9]{4}-[A-Z0-9]{8}$/.test(value);
}
